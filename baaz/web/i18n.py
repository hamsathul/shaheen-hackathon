def lang_of(value: str | None) -> str:
    return value if value in LANGS else "en"


def label(table: dict[str, dict[str, str]], lang: str, key: str | None) -> str:
    """A translated label, or the key itself when the table does not know it."""
    return table[lang].get(key or "", key or "")
